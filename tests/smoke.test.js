'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const os = require('node:os');
const fs = require('node:fs');
const path = require('node:path');
const { createApp } = require('../server');

test('UNLOS account, course, quiz, progress and admin workflow', async t => {
  const folder = fs.mkdtempSync(path.join(os.tmpdir(), 'unlos-test-'));
  const file = path.join(folder, 'db.json');
  const server = createApp({ dataFile: file, adminEmail: 'instructor@example.com', adminPassword: 'a-strong-admin-password' });
  await new Promise(ok => server.listen(0, '127.0.0.1', ok));
  t.after(async () => { await new Promise(ok => server.close(ok)); fs.rmSync(folder, { recursive: true, force: true }); });
  const host = `http://127.0.0.1:${server.address().port}`;
  let cookie = '';
  const api = async (route, method = 'GET', data, useCookie = true) => {
    const response = await fetch(host + route, { method, headers: { ...(data ? { 'Content-Type': 'application/json' } : {}), ...(useCookie && cookie ? { Cookie: cookie } : {}) }, body: data ? JSON.stringify(data) : undefined });
    const json = await response.json();
    const set = response.headers.get('set-cookie'); if (set && useCookie) cookie = set.split(';')[0];
    return { status: response.status, json };
  };
  assert.equal((await api('/api/health')).status, 200);
  let result = await api('/api/courses');
  assert.equal(result.json.courses.length, 4);
  const detailed = await api('/api/courses/web-development');
  assert.equal(detailed.json.course.lessons.length, 4);
  assert.equal('answer' in detailed.json.course.lessons[0].quiz, false);
  assert.equal((await api('/api/dashboard')).status, 401);
  result = await api('/api/auth/register', 'POST', { name: 'Test Learner', email: 'TEST@example.com', password: 'great-password-123' });
  assert.equal(result.status, 201);
  assert.equal(result.json.user.role, 'student');
  assert.equal((await api('/api/me')).json.user.email, 'test@example.com');
  assert.equal((await api('/api/auth/register', 'POST', { name: 'Another', email: 'test@example.com', password: 'another-password' })).status, 409);
  assert.equal((await api('/api/lessons/web-1/complete', 'POST')).status, 403);
  assert.equal((await api('/api/courses/web-development/enroll', 'POST')).status, 200);
  assert.equal((await api('/api/courses/web-development/enroll', 'POST')).status, 200);
  assert.equal((await api('/api/lessons/web-1/quiz', 'POST', { answer: 0 })).json.correct, false);
  assert.equal((await api('/api/lessons/web-1/quiz', 'POST', { answer: 1 })).json.correct, true);
  assert.equal((await api('/api/lessons/web-1/complete', 'POST')).status, 200);
  assert.equal((await api('/api/lessons/web-1/complete', 'POST')).status, 200);
  result = await api('/api/dashboard');
  assert.equal(result.json.stats.enrolledCourses, 1);
  assert.equal(result.json.stats.completedLessons, 1);
  assert.equal(result.json.stats.passedQuizzes, 1);
  assert.equal(result.json.courses[0].progress, 25);
  assert.equal((await api('/api/admin/courses', 'POST', { title: 'Not allowed', description: 'A long enough description for a class.' })).status, 403);
  await api('/api/auth/logout', 'POST');
  assert.equal((await api('/api/me')).json.user, null);
  assert.equal((await api('/api/auth/login', 'POST', { email: 'test@example.com', password: 'incorrect' })).status, 401);
  assert.equal((await api('/api/auth/login', 'POST', { email: 'test@example.com', password: 'great-password-123' })).status, 200);
  assert.equal((await api('/api/dashboard')).json.stats.completedLessons, 1);
  const adminCookieBefore = cookie;
  const adminLogin = await api('/api/auth/login', 'POST', { email: 'instructor@example.com', password: 'a-strong-admin-password' });
  assert.equal(adminLogin.json.user.role, 'admin');
  result = await api('/api/admin/courses', 'POST', { title: 'Computer Networks', description: 'A foundation course covering the basics of networks.', category: 'Development', level: 'Beginner' });
  assert.equal(result.status, 201);
  const slug = result.json.course.slug;
  result = await api(`/api/admin/courses/${slug}/lessons`, 'POST', { title: 'IP fundamentals', content: 'An IP address identifies an interface on a network and helps packets reach destinations.', minutes: 10 });
  assert.equal(result.status, 201);
  assert.equal(result.json.course.lessonCount, 1);
  assert.equal((await api('/api/courses')).json.courses.length, 5);
  const persisted = JSON.parse(fs.readFileSync(file, 'utf8'));
  assert.equal(persisted.courses.length, 5);
  assert.equal(persisted.completions.length, 1);
  assert.ok(adminCookieBefore);
});

test('static assets and HTTP method/origin safeguards', async t => {
  const folder = fs.mkdtempSync(path.join(os.tmpdir(), 'unlos-test-'));
  const server = createApp({ dataFile: path.join(folder, 'db.json') });
  await new Promise(ok => server.listen(0, '127.0.0.1', ok));
  t.after(async () => { await new Promise(ok => server.close(ok)); fs.rmSync(folder, { recursive: true, force: true }); });
  const host = `http://127.0.0.1:${server.address().port}`;
  const root = await fetch(host);
  assert.equal(root.status, 200);
  assert.match(await root.text(), /UNLOS/);
  assert.match(await (await fetch(host + '/styles.css')).text(), /course-card/);
  assert.equal((await fetch(host + '/api/auth/login', { method: 'POST', headers: { Origin: 'https://evil.example', 'Content-Type': 'application/json' }, body: '{}' })).status, 403);
  assert.equal((await fetch(host + '/api/health', { method: 'DELETE' })).status, 405);
});
